class Solution {
    public long countCommas(long n) {

        if (n < 1000)
            return 0;

        else if (n < 1000000)
            return n - 1000 + 1;

        else if (n < 1000000000L)
            return 999000L + 2 * (n - 1000000L + 1);

        else if (n < 1000000000000L)
            return 999000L
                    + 2 * 999000000L+ 3 * (n - 1000000000L + 1);

        else if (n < 1000000000000000L)
            return 999000L
                    + 2 * 999000000L+ 3 * 999000000000L+ 4 * (n - 1000000000000L + 1);

        else if (n < 1000000000000000000L)
            return 999000L + 2 * 999000000L + 3 * 999000000000L + 4 * 999000000000000L+ 5 * (n - 1000000000000000L + 1);

        else
            return 999000L
                    + 2 * 999000000L+ 3 * 999000000000L+ 4 * 999000000000000L+ 5 * 999000000000000000L+ 6 * (n - 1000000000000000000L + 1);
    }
}